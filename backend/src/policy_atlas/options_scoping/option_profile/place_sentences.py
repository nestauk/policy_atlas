"""The place sentences' code: the grouping, the template, the trace check (task 046, amendment 4).

R80; plan S31; contract review C2, C3, C7, PA4-3, PA4-8, PA4-9, PA4-15.
Under "Where it has been evaluated" the card shows one sentence per place of
an option's evaluating documents. The sentence is generated by one call per
option (``option_profile``'s second wave; the prompt is
:mod:`.place_sentences_prompt`); this module holds everything around the call
that is code, so the profile step and the read side share it:

- :class:`PlaceDocument` — one evaluating document (DOI-collapsed) with the
  fields of its first record, built from the membership read
  (:func:`from_membership`) or, on the read side, from the document lines;
- :func:`group_places` — the documents grouped by top-level place: the
  plan's Where country first, then by document count, then name, then one
  last group "No single place" for "multiple countries", "not stated" and
  "other";
- :func:`call_input` — the call's four data blocks, places ``p1 … pN`` and
  documents ``d1 … dM`` across the option;
- :func:`template_sentence` — the code-built sentence for a place the answer
  leaves out, a sentence that fails, a failed call, or an option read before
  the profile step has written its sentences (C7);
- :func:`trace_check` — the lexical check of a generated sentence: numbers,
  strength words and capitalised names against the place's input (C2: a
  lexical check, not a factual one).
"""

