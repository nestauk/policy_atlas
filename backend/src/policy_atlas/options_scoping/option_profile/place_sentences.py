def plural(word: str) -> str:
    """A type word's plural: "analysis" → "analyses", "study" → "studies", else + "s".

    Args:
        word: A singular noun phrase (its last word is pluralised).

    Returns:
        The plural.
    """
    if word.endswith("sis"):
        return word[:-3] + "ses"
    if len(word) > 1 and word.endswith("y") and word[-2] not in "aeiou":
        return word[:-1] + "ies"
    return word + "s"


def type_word(evidence_type: str | None) -> str | None:
    """An evidence type in the template's plain words (:data:`EVIDENCE_TYPE_WORDS`).

    Args:
        evidence_type: The classified type, or ``None``.

    Returns:
        The plain word, the type lower-cased when not listed, ``None`` for no
        type, Unknown and Non-evidence.
    """
    text = _clean(evidence_type)
    if text is None:
        return None
    if text in EVIDENCE_TYPE_WORDS:
        return EVIDENCE_TYPE_WORDS[text]
    return text.casefold()


def _most_common(values: Iterable[str | None]) -> str | None:
    """The commonest value; ``None`` when there is none or two values tie for it."""
    ranked = Counter(values).most_common(2)
    if not ranked or (len(ranked) == 2 and ranked[0][1] == ranked[1][1]):
        return None
    return ranked[0][0]


#: The words that open the qualifying clause of a plan's target unit; the
#: head noun phrase is the text before the first of them ("Children aged 4
#: to 11" from "Children aged 4 to 11 living in the most deprived fifth of
#: areas"; loop 26L, round 2).
_HEAD_CUTS: tuple[str, ...] = (
    " living ",
    " who ",
    " in ",
    " with ",
    " from ",
    " that ",
    " and living ",
)


def head_phrase(text: str | None) -> str | None:
    """A plan text's head noun phrase: the words before its first qualifying clause.

    Args:
        text: The plan's target unit, or ``None``.

    Returns:
        The head phrase (the whole text when no clause opens), or ``None``.
    """
    if not text:
        return text
    cuts = []
    for word in _HEAD_CUTS:
        start = 0
        while (cut := text.find(word, start)) > 0:
            # "not in education" is the head's own clause, not a qualifier.
            before = text[:cut].split()
            if before and before[-1].casefold() not in ("not", "no", "never"):
                cuts.append(cut)
            start = cut + 1
    cut = min(cuts, default=-1)
    return text[:cut].strip() if cut > 0 else text


def _mid_sentence(text: str | None) -> str | None:
    """A plan or kind text as it reads inside a sentence: its first letter
    lower-cased unless the word is an acronym (loop 26L, round 1)."""
    if not text:
        return text
    if len(text) > 1 and text[0].isupper() and text[1].islower():
        return text[0].lower() + text[1:]
    return text


def template_sentence(group: PlaceGroup, *, target_unit: str | None = None) -> str:
    """The template sentence of one place (R80; S31; contract review C7).

    "{Programme}: {n} {strength} {type} with {kind} in {sub-place},
    measuring {outcome}." — every clause dropped when its field is null,
    down to "{n} documents". ``n`` is the place's total; the programme only
    when every document names the same (folded) one; the strength is the
    commonest tier, left out when that is none or two tiers tie; the type the
    commonest evidence type in plain words, plural when ``n`` > 1
    ("documents" for none, a tie, Unknown and Non-evidence); the kind, the
    sub-place and the outcome are the first document's.

    Args:
        group: One place.

    Returns:
        The sentence.
    """
    docs = group.documents
    n = group.documents_total
    names = {doc.programme_name for doc in docs}
    programme = next(iter(names)) if len(names) == 1 and None not in names else None
    strength = _most_common(doc.tier for doc in docs)
    if strength is not None and strength.casefold() == "not rated":
        strength = None
    noun = _most_common(type_word(doc.evidence_type) for doc in docs) or "document"
    noun = noun if n == 1 else plural(noun)
    first = docs[0] if docs else None
    head = " ".join(
        part for part in (str(n), strength.casefold() if strength else None, noun) if part
    )
    kind = first.tried_on_kind if first is not None else None
    if kind and target_unit and _norm(kind) == _norm(target_unit):
        # The plan's words, cut to their head (loop 26L, round 2).
        kind = head_phrase(kind)
    kind = _mid_sentence(kind)
    detail = first.place_detail if first is not None else None
    measured = _mid_sentence(first.measured) if first is not None else None
    sentence = head
    if kind:
        sentence += f" with {kind}"
    if detail:
        sentence += f" in {detail}"
    if measured:
        sentence += f"{',' if kind or detail else ''} measuring {measured}"
    return f"{programme}: {sentence}." if programme else f"{sentence}."


# --- the trace check (S31; PA4-8; C2, C3) -----------------------------------------------


def _norm(text: str) -> str:
    return " ".join(text.replace("’", "'").casefold().split())


def _bounded(needle: str) -> re.Pattern[str]:
    return re.compile(rf"(?<!\w){re.escape(needle)}(?!\w)")


def _contains(texts: Sequence[str], needle: str) -> bool:
    """Whether ``needle`` (normalised) occurs on word boundaries in one of ``texts``."""
    if not needle:
        return False
    pattern = _bounded(needle)
    return any(pattern.search(text) for text in texts)


@dataclass(frozen=True)
class _Token:
    core: str
    start: bool
    break_before: bool
    break_after: bool


def _tokens(sentence: str) -> list[_Token]:
    raws = sentence.split()
    out: list[_Token] = []
    start_next = True
    for raw in raws:
        core = _POSSESSIVE_END.sub("", raw.strip(_EDGE_PUNCTUATION))
        core = core.strip(_EDGE_PUNCTUATION)
        out.append(
            _Token(
                core=core,
                start=start_next,
                break_before=bool(_BREAK_BEFORE.search(raw)),
                break_after=bool(_BREAK_AFTER.search(raw)),
            )
        )
        start_next = bool(_START_AFTER.search(raw))
    return out


def _allowlist(
    group: PlaceGroup,
    *,
    plan_outcomes: Sequence[str],
    vocabulary: Mapping[str, Sequence[str]],
    target_unit: str | None,
) -> list[str]:
    texts: list[str | None] = [group.place]
    for doc in group.documents:
        texts.extend(getattr(doc, field) for field in _ALLOWLIST_FIELDS)
    texts.extend(SCORE_LABELS.values())
    texts.extend(STRENGTH_WORDS)
    texts.extend(EVIDENCE_TYPES)
    for word in EVIDENCE_TYPE_WORDS.values():
        if word is not None:
            texts.extend((word, plural(word)))
    for facet in ("tried_on_kinds", "measures_kinds"):
        texts.extend(vocabulary.get(facet, []))
    texts.extend(plan_outcomes)
    texts.append(target_unit)
    seen: dict[str, None] = {}
    for text in texts:
        if isinstance(text, str) and (normed := _norm(text)):
            seen.setdefault(normed, None)
    return list(seen)


def _counts(group: PlaceGroup) -> set[int]:
    """Every count rule 1 accepts: the total, per-value counts, the rest, distinct values."""
    total = group.documents_total
    counts = {total}
    for field in _COUNTED_FIELDS:
        values = Counter(
            _norm(value) if isinstance(value := getattr(doc, field), str) else None
            for doc in group.documents
        )
        for count in values.values():
            counts.update((count, total - count))
        counts.add(sum(1 for value in values if value is not None))
    return counts


def _number_value(core: str) -> int | None:
    folded = core.casefold()
    if folded in NUMBER_WORDS:
        return NUMBER_WORDS[folded]
    if re.fullmatch(r"\d+", core):
        return int(core)
    if re.fullmatch(r"\d{1,3}(?:,\d{3})+", core):
        return int(core.replace(",", ""))
    return None


def _numbers_pass(tokens: Sequence[_Token], allow: Sequence[str], counts: set[int]) -> bool:
    for index, token in enumerate(tokens):
        value = _number_value(token.core)
        if value is None:
            if re.search(r"\d", token.core) and not _contains(allow, _norm(token.core)):
                return False  # a mixed token with a digit must be an input text's
            continue
        if value in counts:
            continue
        before = tokens[index - 1].core if index > 0 else ""
        after = tokens[index + 1].core if index + 1 < len(tokens) else ""
        if before and _contains(allow, _norm(f"{before} {token.core}")):
            continue
        if after and _contains(allow, _norm(f"{token.core} {after}")):
            continue
        return False
    return True


def _strength_pass(sentence: str, group: PlaceGroup, allow: Sequence[str]) -> bool:
    text = _norm(sentence)
    strength = {_norm(word) for word in (*STRENGTH_WORDS, *SCORE_LABELS.values())}
    masks: list[tuple[int, int]] = [
        (m.start(), m.end())
        for entry in allow
        if entry not in strength
        for m in _bounded(entry).finditer(text)
    ]
    carried = {_norm(doc.tier) if doc.tier else "not rated" for doc in group.documents}
    taken: list[tuple[int, int]] = []
    for word in sorted(STRENGTH_WORDS, key=len, reverse=True):
        for m in _bounded(word).finditer(text):
            span = (m.start(), m.end())
            if any(span[0] < end and start < span[1] for start, end in taken):
                continue
            taken.append(span)
            if any(start <= span[0] and span[1] <= end for start, end in masks):
                continue
            if word not in carried:
                return False
    return True


def _capitalised(core: str) -> bool:
    return bool(core) and core[0].isupper()


def _runs(tokens: Sequence[_Token]) -> list[list[int]]:
    """Maximal runs of capitalised tokens, joined across connectors."""
    runs: list[list[int]] = []
    index = 0
    while index < len(tokens):
        if not _capitalised(tokens[index].core):
            index += 1
            continue
        run = [index]
        while True:
            last = run[-1]
            if tokens[last].break_after:
                break
            nxt = last + 1
            if nxt < len(tokens) and _capitalised(tokens[nxt].core) and not tokens[
                nxt
            ].break_before:
                run.append(nxt)
                continue
            if (
                nxt + 1 < len(tokens)
                and tokens[nxt].core.casefold() in _CONNECTORS
                and not tokens[nxt].break_after
                and not tokens[nxt].break_before
                and _capitalised(tokens[nxt + 1].core)
                and not tokens[nxt + 1].break_before
            ):
                run.extend((nxt, nxt + 1))
                continue
            break
        runs.append(run)
        index = run[-1] + 1
    return runs


def _names_pass(tokens: Sequence[_Token], allow: Sequence[str]) -> bool:
    words = {word for text in allow for word in re.findall(r"[\w'-]+", text)}
    for run in _runs(tokens):
        if _contains(allow, _norm(" ".join(tokens[i].core for i in run))):
            continue
        for i in run:
            core = tokens[i].core
            folded = _norm(core)
            if _capitalised(core) is False and folded in _CONNECTORS:
                continue
            if _contains(allow, folded):
                continue
            if tokens[i].start and (
                folded in SENTENCE_START_WORDS or folded in NUMBER_WORDS or folded in words
            ):
                continue
            return False
    return True


def trace_check(
    sentence: str,
    group: PlaceGroup,
    *,
    plan_outcomes: Sequence[str],
    vocabulary: Mapping[str, Sequence[str]],
    target_unit: str | None = None,
) -> str | None:
    """The lexical trace check of one generated sentence (S31; PA4-8; C2).

    The allowlist of a place is every text field of its documents, the
    place's name, every tier label and evidence type the system knows (and
    the template's plain type words), the list's folded kinds, the plan's
    outcomes and target unit; every comparison case-folded, on word
    boundaries. Three rules, in order:

    1. ``number`` — every integer and every number word "one" … "twenty"
       equals a count of the place's documents (the total; the documents
       sharing one value of the tier, the evidence type, the programme, the
       Tried on kind, the measure or the geography; the total minus such a
       count; the distinct values of one of those fields), or stands in an
       allowlisted text with its neighbouring word ("aged 4", "under five");
       a token mixing digits and letters ("Change4Life",
       "9-to-10-year-olds") must occur in an allowlisted text.
    2. ``strength`` — every strength word (longest first) is the tier of a
       document of the place, unless it sits inside an allowlisted text the
       sentence holds whole ("Strong Start", "moderate-to-vigorous physical
       activity").
    3. ``name`` — every run of capitalised tokens (joined across "of",
       "and", "the", "for", "&", "de") occurs in an allowlisted text, or
       else each of its tokens does; a sentence-start token (the first, or
       one after ".", ":", ";", "!" or "?") may also be a number word, a function word or
       a generic word (:data:`SENTENCE_START_WORDS`) or a word of the
       allowlist.

    It checks that the words come from the input, not that the sentence
    relates them truly (the loop's read does that).

    Args:
        sentence: The generated sentence, stripped.
        group: Its place.
        plan_outcomes: The plan's outcome texts.
        vocabulary: The list's folded kinds (:func:`vocabulary_from_folds`).
        target_unit: The plan's target unit, place stripped.

    Returns:
        ``None`` when the sentence passes, else the failing rule's name.
    """
    allow = _allowlist(
        group, plan_outcomes=plan_outcomes, vocabulary=vocabulary, target_unit=target_unit
    )
    tokens = [token for token in _tokens(sentence) if token.core]
    if not _numbers_pass(tokens, allow, _counts(group)):
        return "number"
    if not _strength_pass(sentence, group, allow):
        return "strength"
    if not _names_pass(tokens, allow):
        return "name"
    return None
