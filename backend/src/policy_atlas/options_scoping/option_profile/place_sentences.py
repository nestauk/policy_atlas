@dataclass(frozen=True)
class PlaceDocument:
    """One evaluating document of an option, DOI-collapsed (S31).

    Attributes:
        doc_key: The document key (``doi:…`` or ``doc:…``).
        role: The document's highest role under the option (always
            ``evaluated`` for a place document).
        place: Its top level as one display name: a country's short English
            name, an unknown country as written, or "multiple countries",
            "not stated" or "other".
        programme_name: The first record's programme name, folded over the
            option.
        unit: The first record's unit, as written.
        tried_on_kind: That unit's folded Tried on kind.
        setting: The first record's setting, as written.
        outcome: The first record's outcome, as written.
        measured: The plan outcome the record measures, in the plan's words,
            else its outcome's folded Measures kind.
        study_geography: The first record's study geography, as written.
        place_detail: That geography when it adds a place below the top level.
        tier: The appraisal's tier label ("Very strong" … "Weak"), or ``None``.
        quality_score: The appraisal's score, or ``None``.
        evidence_type: The classified evidence type, or ``None``.
        year: The publication year, or ``None``.
        title: The order key after the score (the title; the document key
            when no title is known).
    """

    doc_key: str
    role: str
    place: str
    programme_name: str | None
    unit: str | None
    tried_on_kind: str | None
    setting: str | None
    outcome: str | None
    measured: str | None
    study_geography: str | None
    place_detail: str | None
    tier: str | None
    quality_score: int | None
    evidence_type: str | None
    year: int | None
    title: str = ""


@dataclass(frozen=True)
class PlaceGroup:
    """One place's evaluating documents (S31).

    Attributes:
        place_id: ``p1 … pN`` in group order.
        place: The place's display name, or :data:`NO_SINGLE_PLACE`.
        is_where: The place is the plan's Where country.
        documents: Every document of the place, in send order.
        documents_total: Their count (the call sends at most
            :data:`~.place_sentences_prompt.PLACE_DOCUMENTS_MAX`).
    """

    place_id: str
    place: str
    is_where: bool
    documents: tuple[PlaceDocument, ...]
    documents_total: int


def metadata_year(metadata: Mapping[str, object]) -> int | None:
    """The four-digit publication year of a document's metadata, or ``None``.

    One rule for the profile step and the read side: the first of
    ``publication_year``, ``year``, ``publication_date`` and ``published``
    that is an integer or a text starting with four digits.
    """
    for key in ("publication_year", "year", "publication_date", "published"):
        value = metadata.get(key)
        if isinstance(value, int) and not isinstance(value, bool):
            return value
        if isinstance(value, str) and re.match(r"\d{4}", value.strip()):
            return int(value.strip()[:4])
    return None


def place_name(top: str) -> str:
    """A document's top level as the place sentences name it.

    Args:
        top: The top level (:func:`~.where_tried.document_where`).

    Returns:
        The country's short English name when the resolver knows it, else the
        top level as written ("multiple countries", "not stated", "other"
        and an unknown country stay as they are).
    """
    if top in NO_SINGLE_PLACE_TOPS:
        return top
    resolved = resolve_country(top)
    return resolved[1] if resolved is not None else top


def place_detail(study_country: str | None, study_geography: str | None, top: str) -> str | None:
    """A record's place below its document's top level, when it adds one (S30).

    Args:
        study_country: The record's ``study_country``.
        study_geography: The record's ``study_geography``.
        top: The document's top level.

    Returns:
        The geography, unless it is the record's own country, the top level
        itself, or under "multiple countries".
    """
    _country, geography = country_level(study_country, study_geography)
    detail = _clean(geography)
    if detail is None or top == MULTIPLE_COUNTRIES or place_key(detail) == place_key(top):
        return None
    return detail


def tier_label(label: DocumentLabels | None) -> tuple[str | None, int | None, str | None]:
    """``(tier label, quality score, evidence type)`` of a resolved label.

    Args:
        label: The document's labels, or ``None``.

    Returns:
        Three ``None`` for no label or an absent one.
    """
    if label is None or label.provenance == "absent":
        return None, None, None
    score = label.quality_score
    return (
        SCORE_LABELS.get(score) if score is not None else None,
        score,
        label.evidence_type,
    )


def _role_rank(role: str | None) -> int:
    return ROLE_BUCKETS.index(role) if role in ROLE_BUCKETS else len(ROLE_BUCKETS)


def _first_member(members: Sequence[CoverageMember]) -> CoverageMember:
    """The record a document's fields come from: by role order, then its words.

    A membership row carries no creation time, so the order after the role is
    the record's own text (deterministic whatever the row order).
    """
    return min(
        members,
        key=lambda m: (
            _role_rank(m.role),
            m.unit_kind != "interventions",
            tuple(
                _clean(value) or ""
                for value in (
                    m.programme_name,
                    m.unit,
                    m.outcome,
                    m.setting,
                    m.study_geography,
                    m.study_country,
                    m.intervention,
                )
            ),
        ),
    )


def from_membership(
    members: Sequence[CoverageMember],
    *,
    labels: Mapping[uuid.UUID, DocumentLabels],
    folds: Mapping[str, Mapping[str, str]] | None,
    plan_outcomes: Sequence[str],
    programme_fold: Mapping[str, str] | None = None,
    year_by_tss: Mapping[uuid.UUID, int | None] | None = None,
    title_by_tss: Mapping[uuid.UUID, str] | None = None,
) -> list[PlaceDocument]:
    """One option's evaluating documents from its membership read (S31).

    Members group by document key (DOI twins together); a document whose
    members include no ``evaluated`` one is left out (a describing document
    makes no place line, R80). The place is the document's top level over
    every member (a geography that is the record's own country read as the
    country), resolved to one display name; the type and tier are the ones
    coverage counts; the record fields are the first record's.

    Args:
        members: The option's membership rows, as coverage reads them.
        labels: The label resolver's answer per ``tss_id``.
        folds: The list's folding maps, or ``None`` (the records' own words).
        plan_outcomes: The plan's outcome texts.
        programme_fold: Each programme spelling → its shown spelling
            (``fold_programme_names`` over the option); computed from
            ``members`` when ``None``.
        year_by_tss: Each document row's publication year.
        title_by_tss: Each document row's title.

    Returns:
        The documents, in document-key order (:func:`group_places` orders them).
    """
    if programme_fold is None:
        programme_fold = fold_programme_names(
            name for m in members if (name := _clean(m.programme_name)) is not None
        )
    tried_on = fold_lookup(folds, "tried_on") or {}
    measures = fold_lookup(folds, "measures") or {}
    by_doc: dict[str, list[CoverageMember]] = {}
    for member in members:
        by_doc.setdefault(member.doc_key, []).append(member)
    out: list[PlaceDocument] = []
    for key in sorted(by_doc):
        doc_members = by_doc[key]
        if not any(m.role == "evaluated" for m in doc_members):
            continue
        top, _countries = document_where(
            country_level(m.study_country, m.study_geography) for m in doc_members
        )
        first = _first_member(doc_members)
        tier, score, evidence_type = tier_label(document_label(doc_members, labels))
        tss_ids = sorted({m.tss_id for m in doc_members if m.tss_id is not None}, key=str)
        year = next(
            (y for t in tss_ids if (y := (year_by_tss or {}).get(t)) is not None), None
        )
        title = next((t_ for t in tss_ids if (t_ := (title_by_tss or {}).get(t))), key)
        measured = plan_outcome_named(first.outcome_tag, plan_outcomes)
        if measured is None:
            measured = fold_kind(measures, first.outcome)
        name = _clean(first.programme_name)
        out.append(
            PlaceDocument(
                doc_key=key,
                role="evaluated",
                place=place_name(top),
                programme_name=programme_fold.get(name, name) if name is not None else None,
                unit=_clean(first.unit),
                tried_on_kind=fold_kind(tried_on, first.unit),
                setting=_clean(first.setting),
                outcome=_clean(first.outcome),
                measured=measured,
                study_geography=_clean(first.study_geography),
                place_detail=place_detail(first.study_country, first.study_geography, top),
                tier=tier,
                quality_score=score,
                evidence_type=evidence_type,
                year=year,
                title=title,
            )
        )
    return out


def _document_order(doc: PlaceDocument) -> tuple[Any, ...]:
    return (
        _role_rank(doc.role),
        -(doc.quality_score if doc.quality_score is not None else -1),
        doc.title.casefold(),
        doc.doc_key,
    )


def group_places(docs: Iterable[PlaceDocument], *, where_country: str | None) -> list[PlaceGroup]:
    """The evaluating documents grouped by place, in the card's order (R80; S31; PA4-3).

    One group per country (its display name): the plan's Where country
    first, then by document count descending, then name; then one last group
    :data:`NO_SINGLE_PLACE` holding every document whose top level is
    "multiple countries", "not stated" or "other" (absent when empty). Only
    ``evaluated`` documents count. Inside a group the documents are ordered
    by role, then quality score descending (unrated last), then title.

    Args:
        docs: The option's place documents.
        where_country: The plan's Where as one country's display name
            (:func:`~.where_tried.resolve_country`), or ``None``.

    Returns:
        The groups, ``place_id`` ``p1 … pN`` in order.
    """
    countries: dict[str, list[PlaceDocument]] = {}
    shown: dict[str, str] = {}
    no_single: list[PlaceDocument] = []
    for doc in docs:
        if doc.role != "evaluated":
            continue
        if doc.place in NO_SINGLE_PLACE_TOPS:
            no_single.append(doc)
            continue
        key = place_key(doc.place)
        countries.setdefault(key, []).append(doc)
        if key not in shown or doc.place < shown[key]:
            shown[key] = doc.place
    where_key = place_key(where_country) if where_country else None
    ordered = sorted(
        countries,
        key=lambda key: (key != where_key, -len(countries[key]), shown[key].casefold(), key),
    )
    entries: list[tuple[str, bool, list[PlaceDocument]]] = [
        (shown[key], key == where_key, countries[key]) for key in ordered
    ]
    if no_single:
        entries.append((NO_SINGLE_PLACE, False, no_single))
    return [
        PlaceGroup(
            place_id=f"p{index}",
            place=place,
            is_where=is_where,
            documents=tuple(sorted(held, key=_document_order)),
            documents_total=len(held),
        )
        for index, (place, is_where, held) in enumerate(entries, start=1)
    ]


def vocabulary_from_folds(folds: Mapping[str, Mapping[str, str]] | None) -> dict[str, list[str]]:
    """The list's folded kinds, the call's vocabulary (S31).

    Args:
        folds: The list's folding maps, or ``None``.

    Returns:
        ``{"tried_on_kinds": [...], "measures_kinds": [...]}``, each kind once
        (case-folded), in first-seen order.
    """
    out: dict[str, list[str]] = {}
    for facet, key in (("tried_on", "tried_on_kinds"), ("measures", "measures_kinds")):
        stored = (folds or {}).get(facet) or {}
        seen: dict[str, str] = {}
        for kind in stored.values():
            text = _clean(kind) if isinstance(kind, str) else None
            if text is not None:
                seen.setdefault(text.casefold(), text)
        out[key] = list(seen.values())
    return out


def call_input(
    option_name: str,
    option_description: str,
    plan: Mapping[str, object],
    vocabulary: Mapping[str, Sequence[str]],
    groups: Sequence[PlaceGroup],
) -> dict[str, Any]:
    """The place-sentence call's four data blocks (S31; PA4-15).

    Document ids ``d1 … dM`` run across the whole option in group order; a
    place sends its first :data:`~.place_sentences_prompt.PLACE_DOCUMENTS_MAX`
    documents and its total.

    Args:
        option_name: The option's name.
        option_description: Its description.
        plan: The place-stripped plan data (``target_unit`` and ``outcomes``
            are read).
        vocabulary: :func:`vocabulary_from_folds`.
        groups: :func:`group_places`.

    Returns:
        The keyword arguments of ``build_place_sentences_messages``:
        ``{"option", "plan", "vocabulary", "places"}``.
    """
    outcomes = plan.get("outcomes")
    target_unit = plan.get("target_unit")
    places: list[dict[str, Any]] = []
    counter = 0
    for group in groups:
        documents: list[dict[str, Any]] = []
        for doc in group.documents[:PLACE_DOCUMENTS_MAX]:
            counter += 1
            documents.append(
                {
                    "id": f"d{counter}",
                    "programme_name": doc.programme_name,
                    "unit": doc.unit,
                    "tried_on_kind": doc.tried_on_kind,
                    "setting": doc.setting,
                    "outcome": doc.outcome,
                    "measured": doc.measured,
                    "study_geography": doc.study_geography,
                    "tier": doc.tier,
                    # The plain type word the template uses, never the
                    # classifier's label (loop 26L, round 1).
                    "evidence_type": type_word(doc.evidence_type),
                    "year": doc.year,
                }
            )
        places.append(
            {
                "place_id": group.place_id,
                "place": group.place,
                "documents_total": group.documents_total,
                "documents": documents,
            }
        )
    return {
        "option": {"name": option_name, "description": option_description},
        "plan": {
            "target_unit": target_unit if isinstance(target_unit, str) else None,
            "target_unit_short": (
                head_phrase(target_unit) if isinstance(target_unit, str) else None
            ),
            "outcomes": [o for o in outcomes if isinstance(o, str)]
            if isinstance(outcomes, list)
            else [],
        },
        "vocabulary": {
            "tried_on_kinds": list(vocabulary.get("tried_on_kinds", [])),
            "measures_kinds": list(vocabulary.get("measures_kinds", [])),
        },
        "places": places,
    }


